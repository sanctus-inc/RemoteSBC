"""Writes font.h: DejaVu Sans glyphs for ASCII 32-126 as 8-bit coverage bitmaps, for the status bar (no SDL_ttf).
  python3 make_font.py [TTF] [PX] > font.h"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/TTF/DejaVuSans.ttf"
px = int(sys.argv[2]) if len(sys.argv) > 2 else 15
f = ImageFont.truetype(ttf, px)
asc, desc = f.getmetrics()
H = asc + desc
glyphs = []
for c in range(32, 127):
    w = max(1, int(round(f.getlength(chr(c)))))
    im = Image.new("L", (w, H), 0)
    ImageDraw.Draw(im).text((0, 0), chr(c), font=f, fill=255)
    glyphs.append((w, list(im.tobytes())))
print(f"/* generated by make_font.py from {ttf} at {px} px; do not edit */")
print(f"#define FONT_H {H}")
print("static const unsigned char font_w[95] = {" + ",".join(str(w) for w, _ in glyphs) + "};")
offs, o = [], 0
for w, _ in glyphs:
    offs.append(o); o += w * H
print("static const unsigned int font_off[95] = {" + ",".join(map(str, offs)) + "};")
data = [v for _, d in glyphs for v in d]
print(f"static const unsigned char font_px[{len(data)}] = {{")
for i in range(0, len(data), 40):
    print(",".join(map(str, data[i:i + 40])) + ",")
print("};")
